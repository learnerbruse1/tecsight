using TecSight.Core;

namespace TecSight.Core.Tests;

public class PeripheralProbeEdidTests
{
    // 真实 BOE 2560x1600 面板的 EDID 前 128 字节（校验和省略）。
    private static readonly byte[] Edid =
    [
        0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x09, 0xE5, 0x38, 0x0B, 0x03, 0x00, 0x00, 0x00,
        0x20, 0x20, 0x01, 0x04, 0xB5, 0x22, 0x15, 0x78, 0x03, 0xA5, 0xA5, 0xA7, 0x53, 0x4C, 0x9B, 0x25,
        0x0E, 0x50, 0x54, 0x00, 0x00, 0x00, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01,
        0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x90, 0x6F, 0x00, 0xA0, 0xA0, 0x40, 0x96, 0x60, 0x30, 0x20,
        0x36, 0x00, 0x58, 0xD7, 0x10, 0x00, 0x00, 0x1A, 0x00, 0x00, 0x00, 0xFD, 0x0C, 0x3C, 0xA5, 0x21,
        0x21, 0x4F, 0x01, 0x0A, 0x20, 0x20, 0x20, 0x20, 0x20, 0x20, 0x00, 0x00, 0x00, 0xFE, 0x00, 0x42,
        0x4F, 0x45, 0x20, 0x4E, 0x4A, 0x0A, 0x20, 0x20, 0x20, 0x20, 0x20, 0x20, 0x00, 0x00, 0x00, 0xFE,
        0x00, 0x4E, 0x45, 0x31, 0x36, 0x30, 0x51, 0x44, 0x4D, 0x2D, 0x4E, 0x59, 0x43, 0x0A, 0x01, 0x04,
    ];

    [Fact]
    public void ParsePreferredMode_ExtractsNativeResolutionAndRefreshRate()
    {
        var mode = PeripheralProbe.ParsePreferredMode(Edid);

        Assert.NotNull(mode);
        Assert.Equal(2560, mode!.Value.Width);
        Assert.Equal(1600, mode.Value.Height);
        Assert.InRange(mode.Value.RefreshRate, 59.5, 60.5);
    }

    [Fact]
    public void DecodeEisaManufacturer_ExtractsVendorCode()
    {
        Assert.Equal("BOE", PeripheralProbe.DecodeEisaManufacturer(Edid));
    }

    [Fact]
    public void ParseManufactureYear_ExtractsYear()
    {
        Assert.Equal(2022, PeripheralProbe.ParseManufactureYear(Edid));
    }

    [Theory]
    [InlineData(null)]
    [InlineData(new byte[] { })]
    public void EdidHelpers_HandleMissingDataGracefully(byte[]? data)
    {
        Assert.Null(PeripheralProbe.ParsePreferredMode(data));
        Assert.Null(PeripheralProbe.DecodeEisaManufacturer(data));
        Assert.Null(PeripheralProbe.ParseManufactureYear(data));
    }

    [Fact]
    public void ParsePreferredMode_RejectsZeroPixelClock()
    {
        var edid = (byte[])Edid.Clone();
        edid[54] = 0;
        edid[55] = 0;

        Assert.Null(PeripheralProbe.ParsePreferredMode(edid));
    }
}
